module segment_reduce_ragged_mod
  use iso_c_binding
  implicit none
contains
  !> Segmented reduction (dot product) over ragged CSR structure.
  !> Arguments follow the canonical order generated by the benchmark harness:
  !>   out      – output array (NSEG) – double precision
  !>   row_ptr  – segment boundaries (NSEG+1) – int64
  !>   val      – values array (total entries) – double precision
  !>   w        – weights array (total entries) – double precision
  !>   NSEG     – number of segments – int64 (passed by value)
  subroutine segment_reduce_ragged_fp64(out, row_ptr, val, w, NSEG) bind(C, name="segment_reduce_ragged_fp64")
    real(c_double), intent(out) :: out(*)
    integer(c_int64_t), intent(in) :: row_ptr(*)
    real(c_double), intent(in) :: val(*)
    real(c_double), intent(in) :: w(*)
    integer(c_int64_t), value, intent(in) :: NSEG
    integer(c_int64_t) :: s, e, start, endi
    real(c_double) :: acc
    !$omp parallel do schedule(guided) private(s, start, endi, e, acc)
    do s = 0, NSEG - 1
      start = row_ptr(s + 1)          ! row_ptr is 0‑based in C, Fortran 1‑based
      endi  = row_ptr(s + 2) - 1
      acc = 0.0_c_double
      if (start <= endi) then
        !$omp simd reduction(+:acc)
        do e = start, endi
          acc = acc + val(e + 1) * w(e + 1)
        end do
      end if
      out(s + 1) = acc
    end do
    !$omp end parallel do
  end subroutine segment_reduce_ragged_fp64
end module segment_reduce_ragged_mod
