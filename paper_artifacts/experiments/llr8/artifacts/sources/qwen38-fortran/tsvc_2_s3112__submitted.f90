SUBROUTINE tsvc_2_s3112_fp64(A, B, LEN, WORKSPACE, WORKSPACE_BYTES) &
     BIND(C, NAME='tsvc_2_s3112_fp64')
  USE ISO_C_BINDING
  IMPLICIT NONE
  TYPE(C_PTR), VALUE :: A, B, WORKSPACE
  INTEGER(C_INT64_T), VALUE :: LEN, WORKSPACE_BYTES
  INTEGER(C_INT64_T) :: I
  REAL(C_DOUBLE), POINTER :: AP(:), BP(:)
  REAL(C_DOUBLE) :: S
  IF (LEN <= 0) RETURN
  CALL C_F_POINTER(A, AP, [LEN])
  CALL C_F_POINTER(B, BP, [LEN])
  S = 0.0d0
  DO I = 1, LEN
    S = S + AP(I)
    BP(I) = S
  END DO
END SUBROUTINE tsvc_2_s3112_fp64
